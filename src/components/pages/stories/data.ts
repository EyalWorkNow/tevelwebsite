/** Story body keeps the reference rhythm: quote, situation, mapping (list), solution with sub-heads + figures, closing quotes. */
export function story(slug: string) {
  const i = Math.max(0, slugs.stories.indexOf(slug));
  const c = scenarios[i];
  const q = (text: string): Block => ({ t: "quote", text: `“${text}”`, by: BY });
  const body: Block[] = [
    q(c.quotes[0]),
    { t: "h2", text: "המצב: איך זה נראה מבפנים" },
    { t: "p", text: c.situation[0] },
    { t: "p", text: c.situation[1] },
    { t: "p", text: c.situation[2] },
    { t: "h2", text: "מה תבל הייתה ממפה" },
    { t: "p", text: c.mapIntro },
    { t: "ul", items: c.map },
    { t: "h2", text: c.solutionHeading },
    { t: "p", text: c.solutionIntro },
    { t: "h4", text: c.parts[0].h },
    { t: "p", text: c.parts[0].p },
    { t: "img", seed: i + 2 },
    { t: "p", text: c.partsBridge },
    { t: "h4", text: c.parts[1].h },
    { t: "p", text: c.parts[1].p },
    { t: "img", seed: i + 3 },
    { t: "h4", text: c.parts[2].h },
    { t: "p", text: c.parts[2].p },
    q(c.quotes[1]),
    { t: "h2", text: "איזו תוצאה אפשר לצפות" },
    { t: "p", text: c.outcome[0] },
    { t: "p", text: c.outcome[1] },
    q(c.quotes[2]),
  ];
  return {
    ...stories[i],
    lede: `${LABEL}. ${c.lede}`,
    org: c.org,
    industry: c.industry,
    body,
  };
}
