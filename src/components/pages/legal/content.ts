// Block model mirroring the reference's long-form rhythm: h2 / h3 / p / ul / table / hr.
// DRAFT legal copy (Hebrew) — placeholders in [brackets] must be completed and the text reviewed by counsel before publishing.
export type Run = { t: string; b?: boolean; href?: string };
export type Block =
  | { k: "p"; runs: Run[] }
  | { k: "ul"; items: Run[][] }
  | { k: "h2"; text: string; id: string }
  | { k: "h3"; text: string }
  | { k: "table"; head: string[]; rows: Run[][][] }
  | { k: "hr" };

type Doc = { heading: string; lede: string; blocks: Block[] };

const p = (...runs: (string | Run)[]): Block => ({ k: "p", runs: runs.map((r) => (typeof r === "string" ? { t: r } : r)) });
const ul = (...items: (string | [string, string])[]): Block => ({
  k: "ul",
  items: items.map((it) => (typeof it === "string" ? [{ t: it }] : [{ t: it[0] + ".", b: true }, { t: " " + it[1] }])),
});
const h2 = (text: string, id: string): Block => ({ k: "h2", text, id });
const h3 = (text: string): Block => ({ k: "h3", text });
const table = (head: string[], rows: string[][]): Block => ({ k: "table", head, rows: rows.map((r) => r.map((c) => [{ t: c }])) });
const hr: Block = { k: "hr" };
